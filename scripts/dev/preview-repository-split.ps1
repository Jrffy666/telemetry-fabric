        "Generated by scripts/dev/preview-repository-split.ps1 in $Mode mode.",
        "Source repository: $RepoRoot",
        "Review CI, package publishing, and contract dependency wiring before release."
    )
    Set-Utf8NoBomFile -Path (Join-Path $ProjectRoot "SPLIT_ORIGIN.md") -Value $content
}

function Copy-CommonFiles {
    param(
        [Parameter(Mandatory = $true)][string]$ProjectRoot
    )

    foreach ($name in @("LICENSE", ".gitignore", ".gitattributes")) {
        $sourcePath = Join-Path $RepoRoot $name
        if (Test-Path -LiteralPath $sourcePath) {
            Copy-Item -LiteralPath $sourcePath -Destination $ProjectRoot -Force
        }
    }
}

function Replace-InProjectFiles {
    param(
        [Parameter(Mandatory = $true)][string]$ProjectRoot,
        [Parameter(Mandatory = $true)][string[]]$Extensions,
        [Parameter(Mandatory = $true)][string]$Pattern,
        [Parameter(Mandatory = $true)][string]$Replacement
    )

    Get-ChildItem -LiteralPath $ProjectRoot -Recurse -File -Force | Where-Object {
        $Extensions -contains $_.Extension -or $Extensions -contains $_.Name
    } | ForEach-Object {
        $text = Get-Content -LiteralPath $_.FullName -Raw
        $updated = $text -replace [regex]::Escape($Pattern), $Replacement
        if ($updated -ne $text) {
            Set-Utf8NoBomFile -Path $_.FullName -Value $updated -NoNewline
        }
    }
}

