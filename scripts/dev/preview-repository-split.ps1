param(
    [string]$OutputRoot = "",
    [ValidateSet("Preview", "Export")]
    [string]$Mode = "Preview",
    [switch]$Clean
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
if ([string]::IsNullOrWhiteSpace($OutputRoot)) {
    if ($Mode -eq "Export") {
        $OutputRoot = Split-Path -Parent $RepoRoot
    } else {
        $OutputRoot = Join-Path $RepoRoot ".tmp\split-preview"
    }
} elseif (-not [System.IO.Path]::IsPathRooted($OutputRoot)) {
    $OutputRoot = Join-Path $RepoRoot $OutputRoot
}

$OutputRoot = [System.IO.Path]::GetFullPath($OutputRoot)
$TmpRoot = [System.IO.Path]::GetFullPath((Join-Path $RepoRoot ".tmp"))

function Test-IsUnderPath {
    param(
        [Parameter(Mandatory = $true)][string]$Child,
        [Parameter(Mandatory = $true)][string]$Parent
    )

    $childFull = [System.IO.Path]::GetFullPath($Child).TrimEnd('\', '/')
    $parentFull = [System.IO.Path]::GetFullPath($Parent).TrimEnd('\', '/')
    return $childFull.StartsWith($parentFull + [System.IO.Path]::DirectorySeparatorChar, [System.StringComparison]::OrdinalIgnoreCase)
}

if ((Test-Path -LiteralPath $OutputRoot) -and $Clean) {
    if (-not (Test-IsUnderPath -Child $OutputRoot -Parent $TmpRoot)) {
        throw "Refusing to clean output outside .tmp: $OutputRoot. Delete or move existing sibling projects manually if needed."
    }
    Remove-Item -LiteralPath $OutputRoot -Recurse -Force
}

New-Item -ItemType Directory -Force -Path $OutputRoot | Out-Null

function Set-Utf8NoBomFile {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][AllowEmptyString()][object]$Value,
        [switch]$NoNewline
    )

    if ($Value -is [array]) {
        $text = [string]::Join([Environment]::NewLine, [string[]]$Value)
    } else {
        $text = [string]$Value
    }

    if (-not $NoNewline) {
        $text = $text + [Environment]::NewLine
    }

    $encoding = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $text, $encoding)
}

