function Convert-DeployProjectPaths {
    param([Parameter(Mandatory = $true)][string]$ProjectRoot)

    $compose = Join-Path $ProjectRoot "deploy\docker\docker-compose.yml"
    if (Test-Path -LiteralPath $compose) {
        $text = Get-Content -LiteralPath $compose -Raw
        $text = $text -replace "context: \.\./\.\.", "context: ../../.."
        $text = $text -replace "dockerfile: deploy/docker/control-plane\.Dockerfile", "dockerfile: telemetry-fabric-deploy/deploy/docker/control-plane.Dockerfile"
        $text = $text -replace "dockerfile: deploy/docker/telemetry-agent\.Dockerfile", "dockerfile: telemetry-fabric-deploy/deploy/docker/telemetry-agent.Dockerfile"
        Set-Utf8NoBomFile -Path $compose -Value $text -NoNewline
    }

    $controlPlaneDockerfile = Join-Path $ProjectRoot "deploy\docker\control-plane.Dockerfile"
    if (Test-Path -LiteralPath $controlPlaneDockerfile) {
        $text = Get-Content -LiteralPath $controlPlaneDockerfile -Raw
        $text = $text -replace "/workspace/apps/control_plane", "/workspace/telemetry-fabric-core/apps/control_plane"
        $text = $text -replace "COPY apps/control_plane/", "COPY telemetry-fabric-core/apps/control_plane/"
        Set-Utf8NoBomFile -Path $controlPlaneDockerfile -Value $text -NoNewline
    }

    $agentDockerfile = Join-Path $ProjectRoot "deploy\docker\telemetry-agent.Dockerfile"
    if (Test-Path -LiteralPath $agentDockerfile) {
        $text = Get-Content -LiteralPath $agentDockerfile -Raw
        $text = $text -replace "WORKDIR /workspace", "WORKDIR /workspace/telemetry-fabric-core"
        $text = $text -replace "COPY \. \.", "COPY telemetry-fabric-core ."
        Set-Utf8NoBomFile -Path $agentDockerfile -Value $text -NoNewline
    }
}

