function Invoke-ProjectPostProcess {
    param(
        [Parameter(Mandatory = $true)][string]$ProjectRoot,
        [Parameter(Mandatory = $true)][string]$Name
    )

    Copy-CommonFiles -ProjectRoot $ProjectRoot

    switch ($Name) {
        "telemetry-fabric-core" {
            Write-CoreMakefile -ProjectRoot $ProjectRoot
        }
        "telemetry-fabric-contracts" {
            Write-ContractsMakefile -ProjectRoot $ProjectRoot
        }
        "telemetry-chain-crawler-go" {
            Replace-InProjectFiles -ProjectRoot $ProjectRoot -Extensions @(".go", "go.mod", ".md") -Pattern "telemetry-fabric/services/chain-crawler-go" -Replacement "telemetry-chain-crawler-go"
            Replace-InProjectFiles -ProjectRoot $ProjectRoot -Extensions @(".md") -Pattern "cd services/chain-crawler-go" -Replacement "cd telemetry-chain-crawler-go"
            Write-GoMakefile -ProjectRoot $ProjectRoot
        }
        "telemetry-analytics-python" {
            $queryTest = Join-Path $ProjectRoot "tests\test_clickhouse_queries.py"
            if (Test-Path -LiteralPath $queryTest) {
                $text = Get-Content -LiteralPath $queryTest -Raw
                $text = $text -replace "parents\[3\]", "parents[1]"
                Set-Utf8NoBomFile -Path $queryTest -Value $text -NoNewline
            }
            Replace-InProjectFiles -ProjectRoot $ProjectRoot -Extensions @(".md", ".py") -Pattern "services\analytics-python" -Replacement "telemetry-analytics-python"
            Replace-InProjectFiles -ProjectRoot $ProjectRoot -Extensions @(".md", ".py") -Pattern "services/analytics-python" -Replacement "telemetry-analytics-python"
            Write-PythonMakefile -ProjectRoot $ProjectRoot
        }
        "telemetry-compute-accelerator" {
            Replace-InProjectFiles -ProjectRoot $ProjectRoot -Extensions @(".md", "Dockerfile") -Pattern "services/compute-accelerator" -Replacement "telemetry-compute-accelerator"
            $dockerfile = Join-Path $ProjectRoot "docker\Dockerfile"
            if (Test-Path -LiteralPath $dockerfile) {
                $text = Get-Content -LiteralPath $dockerfile -Raw
                $text = $text -replace "/workspace/telemetry-compute-accelerator", "/workspace/telemetry-compute-accelerator"
                Set-Utf8NoBomFile -Path $dockerfile -Value $text -NoNewline
            }
            Write-ComputeMakefile -ProjectRoot $ProjectRoot
        }
        "telemetry-fabric-deploy" {
            Convert-DeployProjectPaths -ProjectRoot $ProjectRoot
            Write-DeployMakefile -ProjectRoot $ProjectRoot
            Write-DeployCi -ProjectRoot $ProjectRoot
        }
    }
}

