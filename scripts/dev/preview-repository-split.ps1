function Copy-DirectoryFiltered {
    param(
        [Parameter(Mandatory = $true)][string]$SourceDirectory,
        [Parameter(Mandatory = $true)][string]$DestinationDirectory
    )

    New-Item -ItemType Directory -Force -Path $DestinationDirectory | Out-Null

    Get-ChildItem -LiteralPath $SourceDirectory -Force | ForEach-Object {
        if ($_.PSIsContainer -and ($ExcludedDirectoryNames -contains $_.Name)) {
            return
        }

        $destinationPath = Join-Path $DestinationDirectory $_.Name
        if ($_.PSIsContainer) {
            Copy-DirectoryFiltered -SourceDirectory $_.FullName -DestinationDirectory $destinationPath
        } else {
            Copy-Item -LiteralPath $_.FullName -Destination $destinationPath -Force
        }
    }
}

function Copy-Entry {
    param(
        [Parameter(Mandatory = $true)][string]$ProjectRoot,
        [Parameter(Mandatory = $true)][string]$Source,
        [Parameter(Mandatory = $true)][string]$Destination
    )

    $sourcePath = Join-Path $RepoRoot $Source
    if (-not (Test-Path -LiteralPath $sourcePath)) {
        Write-Warning "Skipping missing path: $Source"
        return
    }

    $destPath = if ($Destination -eq ".") { $ProjectRoot } else { Join-Path $ProjectRoot $Destination }
    New-Item -ItemType Directory -Force -Path $destPath | Out-Null

    $sourceItem = Get-Item -LiteralPath $sourcePath -Force
    if ($sourceItem.PSIsContainer) {
        Copy-DirectoryFiltered -SourceDirectory $sourcePath -DestinationDirectory $destPath
        return
    }

    Copy-Item -LiteralPath $sourcePath -Destination $destPath -Force
}

function Write-ProjectReadme {
    param(
        [Parameter(Mandatory = $true)][string]$ProjectRoot,
        [Parameter(Mandatory = $true)][string]$Name,
        [Parameter(Mandatory = $true)][string]$Description
    )

    $content = @(
